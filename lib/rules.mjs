/** The telemetry switches between the <telemetry-env> markers in boot-env.ts. */
const telemetryEnvBlock = () => {
  const match = readFile("boot-env.ts").match(/ *\/\/ <telemetry-env>.*\n([\s\S]*?) *\/\/ <\/telemetry-env>\n/);
  if (!match) throw new Error("lib/files/boot-env.ts must contain one <telemetry-env> ... </telemetry-env> block");
  return match[1];
};

/**
 * Packages whose install scripts the desktop build needs (native modules the
 * server loads, the bundler, the typechecker); each takes its prebuilt binary
 * from a lockfile-pinned optional package. Every other allowBuilds entry upstream
 * enables (the mobile app's markdown renderer downloads native frameworks and
 * grammar sources) is turned off in WORK's install and the stage's.
 */
export const DESKTOP_BUILD_SCRIPTS = new Set(["esbuild", "msgpackr-extract", "node-pty", "sharp", "@tsc-rs/typescript"]);

/** pnpm-workspace.yaml with every allowBuilds `true` outside DESKTOP_BUILD_SCRIPTS set to false. */
export function desktopBuildsOnly(yaml) {
  const lines = yaml.split("\n");
  const start = lines.indexOf("allowBuilds:");
  if (start === -1 || lines.indexOf("allowBuilds:", start + 1) !== -1) throw new RuleDrift("pnpm-workspace.yaml: expected one top-level allowBuilds: block", { file: "pnpm-workspace.yaml" });
  for (let i = start + 1; i < lines.length && (lines[i] === "" || /^\s/.test(lines[i])); i++) {
    const entry = /^  ("[^"]+"|'[^']+'|[^\s#:'"]+):\s*(true|false)\s*(#.*)?$/.exec(lines[i]);
    if (!entry) {
      if (/^\s*(#.*)?$/.test(lines[i])) continue;
      throw new RuleDrift(`pnpm-workspace.yaml: can't read allowBuilds line ${JSON.stringify(lines[i])}`, { file: "pnpm-workspace.yaml" });
    }
    const key = entry[1].replace(/^["']|["']$/g, "");
    const name = key.slice(0, key.indexOf("@", 1) === -1 ? key.length : key.indexOf("@", 1));
    if (entry[2] === "true" && !DESKTOP_BUILD_SCRIPTS.has(name)) lines[i] = `  ${entry[1]}: false # t3blackout: the desktop build doesn't need its install script`;
  }
  return lines.join("\n");
}

/** One write rule per file of the Icon Composer bundle in lib/files/app-icon.icon. */
const iconBundleRules = () => {
  const root = path.join(here, "files", "app-icon.icon");
  const files = fs.readdirSync(root, { recursive: true }).filter((rel) => fs.statSync(path.join(root, rel)).isFile());
  return files.sort().map((rel) => ({
    id: `desktop/app-icon-bundle:${rel}`,
    why: "The Redacted app icon, layered for Liquid Glass (compiled by lib/build.mjs when Xcode 26+ is present)",
    kind: "write",
    file: path.join("assets", "blackout", "app-icon.icon", rel),
    content: readBinary(path.join("app-icon.icon", rel)),
  }));
};


/** The build's version and what it changes, baked into the web bundle for the version stamp. */
const buildInfoModule = (build) => {
  const empty = { since: null, repo: null, items: [] };
  const info = {
    version: build?.version ?? null,
    upstreamSha: build?.sha ?? null,
    builtAt: build ? new Date().toISOString() : null,
    upstream: { ...empty, ...build?.changes?.upstream },
    blackout: { ...empty, ...build?.changes?.blackout },
    skipped: build?.skipped ?? [],
  };
  return `// Generated by t3blackout for each build (lib/rules.mjs); null in a dry run.

type Skipped = {
  readonly name: string;
  readonly label: string;
  readonly description: string | null;
  /** anchor: upstream moved the code it hooks into; compile: it no longer compiles; requires: needs a skipped feature. */
  readonly reason: "anchor" | "compile" | "requires";
  readonly requires: string | null;
};

type Changes = {
  readonly since: string | null;
  /** The repository's web URL, for linking commits and pull requests. */
  readonly repo: string | null;
  readonly items: ReadonlyArray<{ readonly sha: string; readonly title: string }>;
};

export const T3BLACKOUT_BUILD: {
  readonly version: string | null;
  readonly upstreamSha: string | null;
  readonly builtAt: string | null;
  readonly upstream: Changes;
  readonly blackout: Changes;
  /** Features this build left out (lib/features.mjs); t3blackoutDrift.ts shows why. */
  readonly skipped: ReadonlyArray<Skipped>;
} = ${JSON.stringify(info, null, 2)};
`;
};

