// backstop for anything new upstream adds before a rule exists for it.

import * as fs from "node:fs";
import * as path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const readFile = (name) => fs.readFileSync(path.join(here, "files", name), "utf8");
const readBinary = (name) => fs.readFileSync(path.join(here, "files", name));

/** The spinner with its verbs filled in from ClaudeSpinner.verbs.txt, which anyone can add to. */
const claudeSpinnerSource = () => {
  const lines = readFile("ClaudeSpinner.verbs.txt").split("\n");
  const verbs = [];
  lines.forEach((raw, i) => {
    const line = raw.trim();
    if (!line || line.startsWith("#")) return;
    const where = `lib/files/ClaudeSpinner.verbs.txt:${i + 1}`;
    if (!/^[A-Z][a-z]*ing$/.test(line)) throw new Error(`${where}: "${line}" must be one capitalized word ending in "ing"`);
    if (verbs.includes(line)) throw new Error(`${where}: "${line}" is listed twice`);
    if (verbs.length && line < verbs.at(-1)) throw new Error(`${where}: "${line}" belongs before "${verbs.at(-1)}"`);
    verbs.push(line);
  });
  const marker = "[/* ClaudeSpinner.verbs.txt */]";
  const source = readFile("ClaudeSpinner.tsx");
  if (source.split(marker).length !== 2) throw new Error(`ClaudeSpinner.tsx must contain ${marker} exactly once`);
  return source.replace(marker, JSON.stringify(verbs));
};

/** One write rule per file of the Icon Composer bundle in lib/files/app-icon.icon. */
const iconBundleRules = () => {
  const root = path.join(here, "files", "app-icon.icon");
  const files = fs.readdirSync(root, { recursive: true }).filter((rel) => fs.statSync(path.join(root, rel)).isFile());
  return files.sort().map((rel) => ({
    id: `desktop/app-icon-bundle:${rel}`,
    why: "The Redacted app icon, layered for Liquid Glass (compiled by lib/build.mjs when Xcode 26+ is present)",
    kind: "write",
    file: path.join("assets", "blackout", "app-icon.icon", rel),
    content: readBinary(path.join("app-icon.icon", rel)),
  }));
};

/**
 * The skills in the repo's skills/ folder, baked into the desktop app for
 * blackoutSkills.ts to place. Each folder is one skill whose SKILL.md
 * frontmatter names it after the folder and describes it.
 */
const blackoutSkillsModule = () => {
  const root = path.join(here, "..", "skills");
  const names = fs.existsSync(root)
    ? fs.readdirSync(root).filter((name) => fs.statSync(path.join(root, name)).isDirectory()).sort()
    : [];
  const skills = names.map((name) => {
    const where = `skills/${name}`;
    if (!/^[a-z0-9][a-z0-9-]*$/.test(name)) throw new Error(`${where}: name folders in lowercase letters, digits and hyphens`);
    const skillFile = path.join(root, name, "SKILL.md");
    if (!fs.existsSync(skillFile)) throw new Error(`${where}: has no SKILL.md`);
    const frontmatter = fs.readFileSync(skillFile, "utf8").match(/^---\n([\s\S]*?)\n---\n/)?.[1];
    if (!frontmatter) throw new Error(`${where}/SKILL.md: must start with --- frontmatter ---`);
    const field = (key) => frontmatter.match(new RegExp(`^${key}:\\s*(.+)$`, "m"))?.[1].trim();
    if (field("name") !== name) throw new Error(`${where}/SKILL.md: name must be "${name}", the folder's name`);
    const description = field("description");
    if (!description) throw new Error(`${where}/SKILL.md: needs a description`);
    const files = fs
      .readdirSync(path.join(root, name), { recursive: true })
      .filter((rel) => !path.basename(rel).startsWith(".") && fs.statSync(path.join(root, name, rel)).isFile())
      .sort()
      .map((rel) => {
        const full = path.join(root, name, rel);
        return {
          path: rel.split(path.sep).join("/"),
          base64: fs.readFileSync(full).toString("base64"),
          executable: (fs.statSync(full).mode & 0o111) !== 0,
        };
      });
    return { name, description, files };
  });
  return `// Generated by t3blackout from the repo's skills/ folder (lib/rules.mjs).

export const BLACKOUT_SKILLS: ReadonlyArray<{
  readonly name: string;
  readonly description: string;
  readonly files: ReadonlyArray<{ readonly path: string; readonly base64: string; readonly executable: boolean }>;
}> = ${JSON.stringify(skills, null, 2)};
`;
};

/** The build's version and what it changes, baked into the web bundle for the version stamp. */
const buildInfoModule = (build) => {
  const empty = { since: null, repo: null, items: [] };
  const info = {
    version: build?.version ?? null,
    upstreamSha: build?.sha ?? null,
    builtAt: build ? new Date().toISOString() : null,
    upstream: { ...empty, ...build?.changes?.upstream },
    blackout: { ...empty, ...build?.changes?.blackout },
  };
  return `// Generated by t3blackout for each build (lib/rules.mjs); null in a dry run.

type Changes = {
  readonly since: string | null;
  /** The repository's web URL, for linking commits and pull requests. */
  readonly repo: string | null;
  readonly items: ReadonlyArray<{ readonly sha: string; readonly title: string }>;
};

export const T3BLACKOUT_BUILD: {
  readonly version: string | null;
  readonly upstreamSha: string | null;
  readonly builtAt: string | null;
  readonly upstream: Changes;
  readonly blackout: Changes;
} = ${JSON.stringify(info, null, 2)};
`;
};

