//
// Each rule targets one choke point, chosen so upstream churn rarely touches it.
// `count` is how many times the anchor must match (see strip-engine.mjs). A
// strict rule that misses stops the update; a rule listed in features.mjs leaves
// its feature out of the build instead. The zero-egress smoke test (lib/smoke.mjs)
// is the backstop for anything new upstream adds before a rule exists for it.

